'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const root = path.join(__dirname, '..');
const readJson = p => JSON.parse(fs.readFileSync(path.join(root, p), 'utf8'));
const classes = readJson('configs/balance/classes.json').classes;
const resources = readJson('configs/balance/resources.json');
const quests = readJson('configs/balance/weekly_quests.json');
const pvp = readJson('configs/balance/pvp_store.json');
const catalog = readJson('configs/skills/catalog.json');
const skills = Array.isArray(catalog) ? catalog : catalog.skills;
const ui = fs.readFileSync(path.join(root, 'rpg-rework-ui.js'), 'utf8');
const css = fs.readFileSync(path.join(root, 'rpg-rework-ui.css.js'), 'utf8');
const html = fs.readFileSync(path.join(root, 'index.html'), 'utf8');

assert.equal(resources.max_resource_by_class.duelist, 100);
assert.deepEqual(resources.class_costs.duelist, { attack_skill: 22, counter: 18, ultimate: 42 });
assert.equal(classes.duelist.resource, 'Тактическая энергия');
assert.equal(classes.duelist.resource_max, 100);
assert.equal(classes.duelist.resource_gain_per_attack, 15);
assert.equal(classes.duelist.resource_gain_on_defense, 1);
assert.equal(classes.duelist.resource_cost_per_skill, 18);
assert.equal(skills.length, 420);
assert.ok(skills.every(s => !/specialization skill|умение специализации\s+[a-z_]+$/i.test(String(s.description || ''))));
assert.ok(skills.every(s => String(s.description || '').trim().length >= 20));
const englishClassIds = /\b(assassin|bishop|dragonkin|destroyer|elemental|duelist|shaman)\b/i;
assert.ok(pvp.items.filter(x => x.category === 'class_epic').every(x => !englishClassIds.test(x.name)));
assert.equal(quests.quests.find(x => x.id === 'heroic')?.name, 'Герой испытаний');
const viewport = html.match(/<meta name="viewport"[^>]*>/i)?.[0] || '';
assert.ok(viewport && !/user-scalable\s*=\s*no/i.test(viewport));
assert.doesNotMatch(ui, /\bilvl\b| рес\./i);
assert.match(ui, /энергии/);
assert.match(ui, /Экипировка класса/);
assert.match(css, /repeat\(auto-fill,minmax\(76px,1fr\)\)/);
assert.match(css, /v2-skill-btn[\s\S]*?min-height:74px/);
assert.match(css, /tb-map-grid[\s\S]*?min-width:374px/);
console.log('UI polish regression checks passed.');

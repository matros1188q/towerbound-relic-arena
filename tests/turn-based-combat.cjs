'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const {createEngine}=require('../rpg-rework-v2.js');
const dir=path.join(__dirname,'../configs/balance');
const balance=Object.fromEntries(fs.readdirSync(dir).filter(x=>x.endsWith('.json')).map(x=>[x.slice(0,-5),JSON.parse(fs.readFileSync(path.join(dir,x),'utf8'))]));
const engine=createEngine(balance,{now:()=>Date.UTC(2026,10,4),random:()=>.25});
const hero=engine.createCharacter('Turn QA','assassin');
assert.equal(balance.combat.turn_based.enabled,true);
assert.equal(engine.maxHp(hero),Math.round(500/1.5*.5),'player max HP is halved');
assert.equal(balance.combat.turn_based.auto_attack_dps_multiplier,.5);
assert.equal(balance.combat.turn_based.skill_dps_multiplier,2.5);
assert.equal(balance.combat.turn_based.ultimate_dps_multiplier,6);
assert.equal(balance.resources.regeneration.auto_attack,.2);
assert.equal(balance.classes.classes.duelist.resource_gain_per_attack,15);
assert.equal(balance.resources.class_costs.duelist.counter,18);
assert.equal(balance.resources.class_costs.duelist.ultimate,42);
assert.equal(balance.combat.turn_based.cooldown_unit,'turns');
const normal=engine.getEnemyStats(hero.id,50,{type:'normal'});
const elite=engine.getEnemyStats(hero.id,50,{type:'elite'});
const boss=engine.getEnemyStats(hero.id,50,{type:'boss'});
assert.deepEqual([normal.hp,normal.damage],[250,50]);
assert.deepEqual([elite.hp,elite.damage],[450,125]);
assert.deepEqual([boss.hp,boss.damage],[1075,350]);
assert.equal(balance.mobs.roles.healer.heal_fraction,.2);
assert.equal(balance.mobs.roles.healer.every_n_turns,2);
assert.equal(balance.mobs.roles.poison.damage_fraction_per_turn,.05);
assert.equal(balance.mobs.roles.tank.shield_fraction,.3);
assert.equal(balance.mobs.roles.tank.every_n_turns,3);
assert.equal(balance.bosses.phases.length,4);
assert.equal(balance.bosses.phases[1].summon_count,2);
assert.equal(balance.bosses.phases[2].immediate_attack,true);
assert.equal(balance.bosses.phases[3].damage_flat,9999);
assert.equal(balance.bosses.phases[3].player_turn_deadline,2);
const ui=fs.readFileSync(path.join(__dirname,'../rpg-rework-ui.js'),'utf8');
assert.match(ui,/function buildInitiative[\s\S]*?sort\(\(a,b\)=>b\.speed-a\.speed/);
assert.match(ui,/a\.type==="player"\?-1:b\.type==="player"\?1/);
assert.match(ui,/data-action="end-turn"/);
assert.doesNotMatch(ui,/class="tb-basic-attack" data-action="attack"/);
assert.match(ui,/function enemyTurn/);
assert.match(ui,/function useCounterSkill/);
assert.match(ui,/function endPlayerTurn/);
assert.match(ui,/potionUsedThisTurn/);
assert.match(ui,/cooldown_turns/);
console.log('Turn-based combat: balance, initiative, player actions, mob roles and boss phases passed.');

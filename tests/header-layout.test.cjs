'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const root=path.join(__dirname,'..');
const read=p=>fs.readFileSync(path.join(root,p),'utf8');
const ui=read('rpg-rework-ui.js');
const css=read('rpg-rework-ui.css.js');
const html=read('index.html');
const sw=read('service-worker.js');
assert.match(ui,/function header\(\)\{return '<header class="tb-header"/,'global header is centralized');
assert.match(ui,/class="game-logo" src="\.\/assets\/icons\/image\.png" alt="T" width="38" height="38"/,'existing T logo remains first and retains its compact display size');
assert.match(ui,/class="tb-brand-title">TowerBound Relic Arena</,'brand title follows the T logo');
assert.doesNotMatch(ui,/data-nav-tab="progress"/,'progression button is removed from global navigation');
assert.match(ui,/button\("open-progress"/,'progression page remains accessible from account');
assert.match(ui,/button\("open-meta-progression"/,'extended progression systems remain accessible from account');
assert.match(ui,/case "open-meta-progression"/,'extended progression account action is wired');
assert.match(ui,/case "bottom-progress":case "open-progress"/,'legacy progression action remains compatible');
assert.match(css,/height:44px!important;min-height:44px!important;max-height:44px!important/,'header is 38px logo plus 5px bottom gap and 1px border');
assert.match(css,/flex-direction:row!important;align-items:center!important;justify-content:flex-start!important/,'header overrides legacy centered vertical layout');
assert.match(css,/width:38px!important;height:38px!important/,'logo display size is fixed rather than allowing intrinsic image dimensions');
assert.match(css,/:has\(\.tb-arena\)>\.tb-header\{display:flex!important\}/,'header remains visible during combat');
assert.doesNotMatch(css,/tb-progression-button/,'obsolete progression-button CSS is removed');
assert.match(html,/rpg-rework-ui\.css\.js\?v=25/,'CSS cache version is updated');
assert.match(html,/rpg-rework-ui\.js\?v=52/,'UI cache version is updated');
assert.match(sw,/towerbound-v453/,'service worker cache is updated');
const progression=read('progression-24.js');
assert.doesNotMatch(progression,/tb-progression-button/,'progression module no longer injects a global header button');
assert.ok(progression.includes("const bar=$('.tb-map-actions',r);"),'secret-room action is limited to the map action area');
assert.match(ui,/root\.innerHTML='<div class="tb-v2">'\+header\(\)\+battleScreen\(\)/,'battle screen receives the shared header');
assert.doesNotMatch(ui,/root\.innerHTML='<div class="tb-v2">'\+header\(\)\+characterList\(\)/,'character selection does not render a duplicate header');
assert.ok((ui.match(/return header\(/g)||[]).length>=8,'standard screens render the shared header from their screen component');
console.log('Towerbound compact header and navigation checks passed.');

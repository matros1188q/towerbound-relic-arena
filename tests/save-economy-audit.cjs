'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const {createEngine}=require('../rpg-rework-v2.js');
const root=path.join(__dirname,'..');
const balanceDir=path.join(root,'configs/balance');
const balance=Object.fromEntries(fs.readdirSync(balanceDir).filter(name=>name.endsWith('.json')).map(name=>[name.slice(0,-5),JSON.parse(fs.readFileSync(path.join(balanceDir,name),'utf8'))]));
let now=Date.UTC(2026,10,18,12);
let randomSeed=0;
const engine=createEngine(balance,{now:()=>++now,random:()=>((randomSeed++*0.61803398875)%1)});
const first=engine.createCharacter('Reward QA','assassin');
const second=engine.createCharacter('Bank QA','bishop');
engine.beginStage(first.id,1);
const stage=engine.getChar(first.id).run.stage;
assert.ok(stage&&stage.mobs.length>=2,'test run begins with a multi-enemy stage');
const beforeSilver=engine.getChar(first.id).silver;
engine.finishEnemy(first.id,{targetIndex:0});
const afterFirst=engine.getChar(first.id);
assert.ok(afterFirst.run.stage.killedIndices.includes(0),'first enemy kill is persisted in the active stage');
assert.ok(afterFirst.silver>beforeSilver,'first enemy kill grants its silver reward');
const rewardBalance=afterFirst.silver;
assert.throws(()=>engine.finishEnemy(first.id,{targetIndex:0}),/already defeated/i,'the same enemy reward cannot be claimed twice in one run');
assert.equal(engine.getChar(first.id).silver,rewardBalance,'duplicate enemy kill does not add silver');
const snapshot=engine.saveSnapshot();
const restored=createEngine(balance,{state:JSON.parse(JSON.stringify(snapshot)),now:()=>++now,random:()=>0.25});
assert.ok(restored.getChar(first.id).run.stage.killedIndices.includes(0),'reload preserves the defeated-enemy ledger');
assert.equal(restored.getChar(first.id).silver,rewardBalance,'reload preserves the already-paid reward');
assert.throws(()=>restored.finishEnemy(first.id,{targetIndex:0}),/already defeated/i,'reload cannot replay a previously paid enemy reward');
const chest=restored.claimDailyChest(first.id);
assert.ok(chest&&chest.type,'daily chest returns one concrete reward');
assert.equal(restored.dailyChestSnapshot(first.id).available,false,'daily chest enters cooldown after claim');
assert.throws(()=>restored.claimDailyChest(first.id),/24 часа/i,'daily chest cannot be claimed twice before cooldown');
const donor=restored.state.characters.find(character=>character.id===first.id);
const receiver=restored.state.characters.find(character=>character.id===second.id);
donor.silver=1000;receiver.silver=0;
const dailyLimit=Math.floor(1000*balance.economy.bank_daily_donor_fraction);
assert.ok(dailyLimit>0,'bank daily transfer limit is configured');
const transfer=restored.transferSilver(first.id,second.id,dailyLimit);
assert.equal(transfer.sent,dailyLimit,'bank transfer respects the configured daily amount');
assert.equal(donor.silver,1000-dailyLimit,'bank transfer debits the donor exactly once');
assert.equal(receiver.silver,transfer.received,'bank transfer credits the receiver net of fees');
assert.throws(()=>restored.transferSilver(first.id,second.id,1),/Daily transfer limit reached/i,'bank transfer limit blocks additional same-day transfers');
assert.throws(()=>restored.transferSilver(first.id,first.id,1),/same character/i,'bank rejects self-transfers');
assert.equal(restored.getChar(first.id).run.stage.killedIndices.filter(index=>index===0).length,1,'saved kill ledger contains no duplicate indices');
console.log('SAVE + ECONOMY AUDIT PASS: active-run reload, single-claim enemy rewards, daily chest cooldown, bank fees and daily transfer limits.');

'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const root=path.join(__dirname,'..');
const progression=fs.readFileSync(path.join(root,'progression-24.js'),'utf8');
const html=fs.readFileSync(path.join(root,'index.html'),'utf8');
const sw=fs.readFileSync(path.join(root,'service-worker.js'),'utf8');
for(const tab of ['progress','economy','ux','lore'])assert.ok(progression.includes('data-progress-tab="'+tab+'"'),'progression tab '+tab+' is rendered');
assert.match(progression,/role="tablist"/,'progression navigation is an accessible tablist');
assert.match(progression,/aria-selected=/,'selected progression tab is exposed to assistive technology');
assert.match(progression,/if\(currentTab==='economy'\)body=/,'economy tab has its own content renderer');
assert.match(progression,/overlay\.addEventListener\('click',e=>\{const t=e\.target\.closest\('\[data-progress-tab\]'\)/,'progression tabs use delegated click handling');
assert.match(progression,/\.tbp-modal\{display:flex;flex-direction:column/,'progression modal uses a constrained flex layout');
assert.match(progression,/\.tbp-content\{flex:1 1 auto;min-height:0;overflow:auto/,'progression content remains scrollable inside the modal');
assert.match(progression,/\.tbp-grid\{grid-template-columns:minmax\(0,1fr\)\}/,'progression cards use a single column on narrow phones');
assert.match(progression,/async function act\(a\)/,'progression actions support asynchronous cloud operations');
assert.match(progression,/await cloud\.syncNow\(\)/,'cloud save action invokes the real authenticated sync flow');
assert.match(progression,/cloud\.open\(\)/,'cloud save action opens account login when needed');
assert.doesNotMatch(progression,/secret\.addEventListener\('click'/,'secret-room reward is handled once by the overlay delegated click handler');
assert.doesNotMatch(progression,/tb-progression-cloud-draft|Google\/Apple OAuth не подключён/,'obsolete local-only cloud-save placeholder is removed');
assert.match(progression,/Сохранение Towerbound через игровой аккаунт/,'cloud-save card describes the actual account-based service');
assert.match(html,/progression-24\.js\?v=9/,'progression UI asset cache version is bumped');
assert.match(sw,/towerbound-v\\d+/,'service worker cache is versioned to prevent stale UI on iOS');
const actionStart=progression.indexOf('async function act(a){');
const actionEnd=progression.indexOf('function inject(){',actionStart);
assert.ok(actionStart>=0&&actionEnd>actionStart,'progression action dispatcher exists');
const actionHandler=progression.slice(actionStart,actionEnd);
const renderedActions=new Set([...progression.matchAll(/data-tbp="([a-z-]+)"/g)].map(match=>match[1]));
for(const match of progression.matchAll(/dataset\.tbp='([a-z-]+)'/g))renderedActions.add(match[1]);
const handledActions=new Set([...actionHandler.matchAll(/case'([^']+)'/g)].map(match=>match[1]));
for(const action of renderedActions)assert.ok(handledActions.has(action),'rendered progression action '+action+' has a handler');
assert.match(progression,/settings\.disable_telegraphs\?'Включить':'Отключить'/,'telegraph toggle reflects the global setting');
assert.match(progression,/settings\.disable_particles\?'Включить частицы':'Отключить частицы'/,'particle toggle reflects the global setting');
console.log('Towerbound progression interface checks passed: 4 tabs, mobile modal, real cloud sync action.');

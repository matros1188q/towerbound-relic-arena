'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const root=path.join(__dirname,'..');
const read=p=>JSON.parse(fs.readFileSync(path.join(root,p),'utf8'));
const names=['combat','xp_curve','map','elite_mechanics','death','healing','auto_battle','drop_tables','equipment','economy','heroic','pvp','classes','skill_effects','mobs','bosses','character_curves','item_level','bp','difficulty','materials','account','stash','tutorial','achievements','lore','settings','seasons','paragon','pvp_store'];
const balance=Object.fromEntries(names.map(name=>[name,read('configs/balance/'+name+'.json')]));
const {createEngine}=require('../rpg-rework-v2.js');
const engine=createEngine(balance,{random:()=>0.2,now:()=>Date.UTC(2026,10,13)});
const created=engine.createCharacter('Math QA','assassin');
const c=engine.state.characters.find(x=>x.id===created.id);
c.level=10;c.talentPoints=9;
const branch=balance.classes.classes.assassin.branches[0];
engine.chooseBranch(c.id,branch.id);
const beforeWeaponBP=engine.combatPower(c),beforeWeaponAttack=engine.getCombatStats(c).attack;
const weapon={id:'qa-weapon-plus-ten',type:'equipment',rarity:'Редкая',slot:'weapon',itemLevel:1,classId:'assassin',branch:branch.id,stats:{attack:10}};
c.bag.push(weapon);
engine.equipItem(c.id,weapon.id);
assert.ok(engine.getCombatStats(c).attack>beforeWeaponAttack,'+10 weapon attack increases live combat attack');
assert.ok(engine.combatPower(c)>beforeWeaponBP,'equipping +10 weapon attack increases BP');
const afterWeaponBP=engine.combatPower(c),beforeTalentAttack=engine.getCombatStats(c).attack;
const attackTalent=branch.talents.find(t=>t.effect_template==='attack');
assert.ok(attackTalent,'assassin branch exposes an attack talent');
engine.useTalentPoint(c.id,attackTalent.id);
assert.ok(engine.getCombatStats(c).attack>beforeTalentAttack,'attack talent increases live combat attack');
assert.ok(engine.combatPower(c)>=afterWeaponBP,'attack talent is reflected in BP');
const ui=fs.readFileSync(path.join(root,'rpg-rework-ui.js'),'utf8');
assert.match(ui,/type==="cost"\?1-\.2\*stacks/,'Economy upgrade reduces skill resource cost by 20% per rank');
assert.match(ui,/type==="power"\?1\+\.2\*stacks/,'Power upgrade increases skill effect by 20% per rank');
assert.match(ui,/let cost=skillStats\.cost/,'battle action spends the upgraded skill cost');
assert.match(ui,/\*skillStats\.powerMultiplier/,'battle action uses the upgraded skill power');
console.log('Progression math checks passed: +10 weapon attack changes live stats and BP; attack talent changes combat attack; skill Economy/Power upgrades feed actual battle calculations.');

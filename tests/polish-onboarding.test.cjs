'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const root=path.join(__dirname,'..');
const read=p=>fs.readFileSync(path.join(root,p),'utf8');
const polish=read('towerbound-polish.js');
const ui=read('rpg-rework-ui.js');
const index=read('index.html');
const sw=read('service-worker.js');
const tutorial=JSON.parse(read('configs/balance/tutorial.json'));
const seasons=JSON.parse(read('configs/balance/seasons.json'));
const endgame=read('endgame-systems.js');
assert.match(index,/towerbound-polish\\.js\\?v=\\d+/,'polish module is loaded with a versioned cache key');
assert.ok(sw.includes('./towerbound-polish.js'),'polish module is included in offline shell cache');
assert.match(sw,/^const CACHE = 'towerbound-v\d+';$/m,'offline shell cache uses a versioned release key');
assert.ok(ui.includes('CARD_DATABASE')&&ui.includes('function drawCards(amount)')&&ui.includes('function playCard(cardIndex)'),'card deckbuilder runtime is wired into the battle UI');
assert.ok(polish.includes('250 этапов'),'new character guide explains the 250-stage goal');
assert.ok(polish.includes('на 10 уровне выбери одну из трёх веток'),'new character guide explains specialization unlock');
assert.ok(!polish.includes('const tutorialSteps=[')&&!polish.includes('function tutorialClick'),'blocking first-battle tutorial controller is absent');
assert.ok(ui.includes('showTutorial:false'),'new battles do not request the full-screen battle tutorial');
assert.ok(!ui.includes('class="tb-turn-tutorial"'),'battle markup contains no full-screen tutorial overlay');
assert.ok(!polish.includes('Шаг 1 из 4'),'old guided battle steps are not reintroduced');
assert.ok(polish.includes('БОЕВАЯ МОЩЬ')&&polish.includes('ЗАЩИТА')&&polish.includes('КРИТ'),'stat info buttons explain power, armor and critical chance');
assert.ok(polish.includes('function showLevelUp')&&polish.includes('Доступно очков талантов'),'level-up reward modal shows talent points');
assert.ok(polish.includes('function lootTone')&&polish.includes('navigator.vibrate'),'high-rarity loot has synthesized audio and vibration feedback');
assert.ok(ui.includes('const bestEquippedSet=')&&ui.includes('item?.setId'),'avatar frame follows the strongest equipped set');
assert.ok(polish.includes('tb-equip-upgrade')&&polish.includes('НАДЕТЬ · ЛУЧШЕ'),'better equipment receives an emphasized equip action');
assert.equal(tutorial.steps_data.length,6,'existing six-step general tutorial remains intact');
assert.ok(endgame.includes('function startTower()'),'existing endless tower remains intact');
assert.equal(seasons.season_length_days,30,'season rotation is configured for a monthly 30-day cycle');
assert.ok(ui.includes('function finishCurrentEnemy')&&ui.includes('function save()'),'core combat and save paths remain present');
console.log('Towerbound polish checks passed: onboarding, action-guided battle tutorial, stat help, level-up feedback, loot feel, equipment comparison, offline cache and existing endgame.');
